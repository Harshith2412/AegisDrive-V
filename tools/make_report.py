#!/usr/bin/env python3
"""Generate results/vertical_slice_report.md purely from machine-generated result files."""
from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def _load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def _cpp_counts():
    d = _load("cpp_test_results.json")
    if not d:
        return None
    tests = [t for s in d["testsuites"] for t in s["testsuite"]]
    return len(tests), sum(1 for t in tests if t.get("failures")), d.get("framework", "googletest")


def _py_counts():
    d = _load("python_test_results.json")
    if d:
        return len(d["tests"]), sum(not t["passed"] for t in d["tests"]), d["framework"]
    x = R / "python_test_results.xml"
    if x.exists():
        import xml.etree.ElementTree as ET
        tc = list(ET.parse(x).getroot().iter("testcase"))
        return len(tc), sum(any(c.tag in ("failure", "error") for c in t) for t in tc), "pytest"
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-kind", default="unknown")
    a = ap.parse_args()
    cc = subprocess.run(["c++", "--version"], capture_output=True, text=True).stdout.splitlines()
    env = {"platform": platform.platform(), "python": platform.python_version(), "compiler": cc[0] if cc else "?",
           "build_kind": a.build_kind}
    for mod in ("numpy", "matplotlib", "yaml", "pytest", "can"):
        try:
            env[mod] = __import__(mod).__version__
        except Exception:  # noqa: BLE001
            env[mod] = "not installed"
    (R / "environment.json").write_text(json.dumps(env, indent=2))

    vs, tr, cov = _load("vertical_slice_results.json"), _load("traceability_matrix.json"), _load("cpp_coverage.json")
    L = ["# AegisDrive-V — Vertical Slice Results (generated)", "",
         "> Generated by `tools/make_report.py` from files in `results/`. Do not edit by hand.", "",
         "## Environment", ""] + [f"- **{k}**: {v}" for k, v in env.items()] + [""]
    L += ["## Test execution", "", "| Level | Framework | Tests | Failed |", "|---|---|---|---|"]
    if (c := _cpp_counts()):
        L.append(f"| C++ unit (ECU core) | {c[2]} | {c[0]} | {c[1]} |")
    if (p := _py_counts()):
        L.append(f"| Python integration / system / fault injection | {p[2]} | {p[0]} | {p[1]} |")
    L.append("")
    if cov:
        L += ["## Structural coverage (C++ unit tests, GCC gcov)", "", "| File | Lines | Line % | Branches | Branch-taken % |",
              "|---|---|---|---|---|"]
        L += [f"| {k} | {v['lines']} | {v['line_pct']} | {v['branches']} | {v['branch_taken_pct']} |"
              for k, v in cov.items() if not k.startswith("_")]
        L += ["", f"_{cov['_note']}_", ""]
    if tr:
        L += ["## Traceability", "", f"- Requirements: **{tr['requirements']}**, tagged tests: **{tr['tests_tagged']}**",
              f"- Status: {tr['status_counts']}", f"- Checker errors: **{len(tr['errors'])}**",
              "- Full matrix: `results/traceability_matrix.md`", ""]
    if vs:
        L += ["## Scenario results (closed loop, real C++ ECUs)", "",
              f"Seeds: {vs['seeds'][0]}–{vs['seeds'][-1]} ({len(vs['seeds'])} per scenario). Collision-rate intervals: Wilson 95 %.", "",
              "| Scenario | Collisions | 95 % CI | Brake requested | Mean TTC at brake [s] | Min gap (min/mean) [m] | Impact [km/h] | Degraded | Brake timeout |",
              "|---|---|---|---|---|---|---|---|---|"]
        for s in vs["scenarios"]:
            L.append(f"| {s['scenario']} {s['title']} | {s['collisions']}/{s['runs']} | {s['collision_rate_ci95'][0]:.2f}–{s['collision_rate_ci95'][1]:.2f} | "
                     f"{s['brake_requested_runs']}/{s['runs']} | {s['mean_ttc_at_brake_request_s']} | {s['min_gap_m_min']} / {s['min_gap_m_mean']} | "
                     f"{s['mean_impact_speed_kph_if_collision'] or '—'} | {s['degraded_runs']} | {s['brake_timeout_runs']} |")
        d = vs["seed0_details"]
        L += ["", "### Seed-0 timing details", "", "| Scenario | First warning [s] | First brake request [s] | Brake active [s] | Brake lamp latency [ms] | Hazard | States |",
              "|---|---|---|---|---|---|---|"]
        for k, r in d.items():
            L.append(f"| {k} | {r['first_warning_s']} | {r['first_brake_request_s']} | {r['first_brake_active_s']} | {r['brake_lamp_latency_ms']} | "
                     f"{r['hazard_activated']} | {' → '.join(r['states_visited'])} |")
        L += ["", "## PRELIMINARY sweep — stationary target (S03 geometry), ego speed × friction", "",
              "| mu | Ego [km/h] | Collisions | 95 % CI | Mean impact [km/h] | Mean min gap [m] |", "|---|---|---|---|---|---|"]
        for s in vs["sweep_stationary"]:
            L.append(f"| {s['mu']} | {s['ego_kph']} | {s['collisions']}/{s['runs']} | {s['ci95_low']:.2f}–{s['ci95_high']:.2f} | {s['mean_impact_kph']} | {s['mean_min_gap_m']} |")
        L += ["", f"_{vs['note']}_", "", "Plots: `results/plots/*.png`. Traces: `results/traces/*.csv`.", ""]
    L += ["## Interpretation and limitations", "",
          "See `docs/open_issues.md` (OI-001…OI-013) and `docs/04_assumptions_limitations.md`. In particular: FI01/FI02 collisions",
          "are expected consequences of documented architecture gaps (single sensor; no brake-feedback monitoring), mu = 0.5 lies",
          "outside the ODD, and 0/20 observed failures bound the failure rate only below ≈16 % (95 %).", ""]
    (R / "vertical_slice_report.md").write_text("\n".join(L))
    print("wrote results/vertical_slice_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
